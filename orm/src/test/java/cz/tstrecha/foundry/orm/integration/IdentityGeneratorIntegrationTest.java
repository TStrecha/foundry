package cz.tstrecha.foundry.orm.integration;

import cz.tstrecha.foundry.orm.FoundryContext;
import cz.tstrecha.foundry.orm.config.FoundryConfiguration;
import cz.tstrecha.foundry.orm.fixtures.identitygen.IdentityGenMarker;
import cz.tstrecha.foundry.orm.fixtures.identitygen.IdentityWidgetEntity;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.HashSet;
import java.util.List;

import static org.assertj.core.api.Assertions.assertThat;

/**
 * Behavior-first contract for the IDENTITY id generator.
 *
 * <p>These tests describe what persist(entity) must do when the entity carries
 * {@code @GeneratedValue(strategy = IDENTITY)}. They avoid naming any internal
 * production type (no IdentityGenerator, no PostInsert, no RETURNING SQL) so the
 * implementation is free to evolve — the only thing being pinned down is the
 * observable outcome: after persist the entity has a non-null id, the row is
 * findable by that id, and two persists never collide.
 *
 * <p>The schema uses PostgreSQL's SQL-standard {@code GENERATED BY DEFAULT AS
 * IDENTITY}, which lets the caller still supply an explicit id if they want to
 * — the "BY DEFAULT" variant is what matches the JPA contract where a non-null
 * id from the caller must be respected.
 */
class IdentityGeneratorIntegrationTest extends AbstractPostgresIntegrationTest {

    private static FoundryContext context;

    @BeforeAll
    static void setupSchema() throws Exception {
        execute("""
                CREATE TABLE IF NOT EXISTS identity_widget (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    label TEXT
                );
                """);
        var config = FoundryConfiguration.builder()
                .url(jdbcUrl).user(user).password(password)
                .scanningRoots(List.of(IdentityGenMarker.class))
                .build();
        context = new FoundryContext(config);
    }

    @BeforeEach
    void cleanTable() throws Exception {
        execute("TRUNCATE identity_widget RESTART IDENTITY;");
    }

    private IdentityWidgetEntity widget(String label) {
        var w = new IdentityWidgetEntity();
        w.setLabel(label);
        return w;
    }

    @Test
    void persistWithNullIdPopulatesIdOnTheEntityInstance() throws Exception {
        var w = widget("alpha");
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> em.persist(w));
        }

        assertThat(w.getId())
                .as("after persist the caller's instance must carry the id the database generated — otherwise the entity is unusable (cannot be looked up, cannot be joined to) immediately after being created")
                .isNotNull();
    }

    @Test
    void persistTwoEntitiesWithNullIdAssignsDistinctIds() throws Exception {
        var a = widget("A");
        var b = widget("B");
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> {
                em.persist(a);
                em.persist(b);
            });
        }

        assertThat(a.getId()).isNotNull();
        assertThat(b.getId()).isNotNull();
        assertThat(a.getId())
                .as("two persists must not share an id — the whole point of IDENTITY is that the database guarantees uniqueness")
                .isNotEqualTo(b.getId());
    }

    @Test
    void persistedEntityIsFindableByItsGeneratedId() throws Exception {
        var w = widget("findable");
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> em.persist(w));
        }

        try (var em = context.openSession()) {
            var found = em.find(IdentityWidgetEntity.class, w.getId()).orElseThrow();
            assertThat(found.getLabel())
                    .as("the id handed back to the caller must identify the row that was just written — otherwise the pipeline round-tripped a different value than what the database actually assigned")
                    .isEqualTo("findable");
        }
    }

    @Test
    void firstPersistAfterTruncateRestartYieldsIdOne() throws Exception {
        var w = widget("first");
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> em.persist(w));
        }

        assertThat(w.getId())
                .as("TRUNCATE ... RESTART IDENTITY resets the backing counter to its START WITH, which defaults to 1 — proves the ORM is actually pulling its value from the database's identity column, not from a counter it invented")
                .isEqualTo(1L);
    }

    @Test
    void persistingManyEntitiesInOneTransactionAssignsStrictlyIncreasingIds() throws Exception {
        var ws = List.of(widget("1"), widget("2"), widget("3"), widget("4"), widget("5"));
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> ws.forEach(em::persist));
        }

        var ids = ws.stream().map(IdentityWidgetEntity::getId).toList();
        assertThat(ids).doesNotContainNull();
        assertThat(new HashSet<>(ids))
                .as("each persist within one transaction must get its own id — no duplicates even without a commit between them")
                .hasSameSizeAs(ids);
        assertThat(ids)
                .as("an identity-backed sequence yields monotonically increasing ids — otherwise ordering invariants callers rely on break")
                .isSorted();
    }

    @Test
    void persistWithCallerSuppliedIdKeepsThatId() throws Exception {
        var w = widget("preassigned");
        w.setId(777L);

        try (var em = context.openSession()) {
            em.runInTransaction(tx -> em.persist(w));
        }

        assertThat(w.getId())
                .as("JPA contract: if the caller supplies an id, the generator must not overwrite it — otherwise explicit control (data migration, deterministic test fixtures) is impossible")
                .isEqualTo(777L);

        try (var em = context.openSession()) {
            var found = em.find(IdentityWidgetEntity.class, 777L).orElseThrow();
            assertThat(found.getLabel())
                    .as("the caller-supplied id must also be what the row ends up stored under in the database")
                    .isEqualTo("preassigned");
        }
    }

    @Test
    void generatedIdRoundTripsIntactThroughTheDatabase() throws Exception {
        var w = widget("roundtrip");
        try (var em = context.openSession()) {
            em.runInTransaction(tx -> em.persist(w));
        }
        var generated = w.getId();

        try (var em = context.openSession()) {
            var found = em.find(IdentityWidgetEntity.class, generated).orElseThrow();
            assertThat(found.getId())
                    .as("the id stored in the row must equal the one that was handed back after insert — otherwise the write and the read are using different values")
                    .isEqualTo(generated);
        }
    }
}
